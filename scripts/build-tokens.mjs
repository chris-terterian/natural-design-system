// Generates src/styles/tokens.css, src/styles/tokens-deprecated.css and the DESIGN.md front matter from
// tokens/figma-variables.json (the mirror of the Figma variables).
// Architecture (D-030): Primitives → Color / Dimension (semantic) → Layout / Typography (responsive roles) → Component
// (one-offs). Every non-primitive token aliases a primitive, so each CSS variable is one var() hop from a raw value.
// Moded collections (Desktop / Mobile) emit Desktop on :root, Mobile under the page breakpoint and under
// [data-nds-mode='mobile'] (like a frame's mode in Figma), plus constants --<token>--desktop / --<token>--mobile so a
// component that switches on its own width (container query) can pick a mode explicitly.
// Color has Light / Dark modes (D-035). Light is the default. Dark is opt-in per subtree with [data-nds-theme='dark'],
// or follows the OS with [data-nds-theme='system'] + prefers-color-scheme: dark. A separate attribute from
// data-nds-mode, so a frame can be Dark and Mobile at once.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../tokens/figma-variables.json', import.meta.url)));
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url)));
const cssName = (name) => `--nds-${name.replaceAll('/', '-')}`;
const px = (n) => `${n}px`;
const collections = Object.entries(src).filter(([name]) => !name.startsWith('$'));
const MODE_MEDIA = { Mobile: '(max-width: 767px)' };

const cssValue = (token) => (token.alias ? `var(${cssName(token.alias)})` : token.type === 'COLOR' ? token.value : px(token.value));

// ---- tokens.css ----
// Brand (D-036) and Color (D-035) are two independent axes: Brand picks the palette family behind each palette step
// (data-nds-brand), Color picks Light or Dark values for each role (data-nds-theme). A CSS variable resolves where
// it is declared, so the roles (which point at palette steps) are re-declared on every element that sets a brand or a
// theme; otherwise a Tide section would keep Natural's colours. Set both attributes on the same element (the page or
// a section); a brand set inside a dark section follows that section's theme.
const BRAND = 'Brand', COLOR = 'Color';
const css = ['/* Generated by scripts/build-tokens.mjs — do not edit by hand. */', ':root {'];
const modeBlocks = {}; // Layout / Typography / Component modes (Desktop / Mobile) and Brand modes: modeName -> lines
const role = { light: [], dark: [], constants: [] };
for (const [collection, vars] of collections) {
  css.push(`  /* ${collection} */`);
  for (const [name, token] of Object.entries(vars)) {
    if (collection === COLOR) { // emitted in the theme blocks below
      for (const [m, t] of Object.entries(token.modes)) role.constants.push(`  ${cssName(name)}--${m.toLowerCase()}: ${cssValue({ ...token, ...t })};`);
      role.light.push(`  ${cssName(name)}: var(${cssName(name)}--light);`);
      role.dark.push(`  ${cssName(name)}: var(${cssName(name)}--dark);`);
      continue;
    }
    if (token.modes) {
      const modes = Object.keys(token.modes);
      css.push(`  ${cssName(name)}: ${cssValue({ ...token, ...token.modes[modes[0]] })};`);
      for (const m of modes) {
        css.push(`  ${cssName(name)}--${m.toLowerCase()}: ${cssValue({ ...token, ...token.modes[m] })};`);
        (modeBlocks[m] ??= []).push(`  ${cssName(name)}: var(${cssName(name)}--${m.toLowerCase()});`);
      }
    } else {
      css.push(`  ${cssName(name)}: ${cssValue(token)};`);
    }
  }
}
css.push('}');
for (const [mode, lines] of Object.entries(modeBlocks)) {
  const media = MODE_MEDIA[mode];
  if (media) css.push('', `@media ${media} {`, '  :root {', ...lines.map((l) => '  ' + l), '  }', '}');
}
const brandModes = Object.keys(Object.values(src[BRAND] || {})[0]?.modes || {});
for (const [mode, lines] of Object.entries(modeBlocks)) {
  if (brandModes.includes(mode)) continue;
  css.push('', `/* Force ${mode} values for a subtree (mirrors setting a frame's mode in Figma) */`, `[data-nds-mode='${mode.toLowerCase()}'] {`, ...lines, '}');
}
for (const mode of brandModes) {
  css.push('', `/* ${mode} brand palette for a subtree (mirrors setting a frame's Brand mode in Figma) */`, `[data-nds-brand='${mode.toLowerCase()}'] {`, ...modeBlocks[mode], '}');
}
// Color roles: Light by default, re-declared wherever a brand or theme is set so they pick up that palette.
const darkScope = "[data-nds-theme='dark'], [data-nds-theme='dark'] [data-nds-brand]:not([data-nds-theme])";
const systemScope = "[data-nds-theme='system'], [data-nds-theme='system'] [data-nds-brand]:not([data-nds-theme])";
css.push('', '/* Color roles (Light by default). Re-declared on every element that sets a brand or a theme. */', ":root, [data-nds-brand], [data-nds-theme] {", ...role.constants, ...role.light, '}');
css.push('', "[data-nds-theme='light'] {", '  color-scheme: light;', '}');
css.push('', "/* Dark theme for a subtree (mirrors setting a frame's Color mode in Figma) */", `${darkScope} {`, '  color-scheme: dark;', ...role.dark, '}');
css.push('', '/* Follow the OS setting where the page opts in with data-nds-theme="system" */', '@media (prefers-color-scheme: dark) {', `  ${systemScope} {`, '    color-scheme: dark;', ...role.dark.map((l) => '  ' + l), '  }', '}');
css.push('');
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css.join('\n'));

// ---- tokens-deprecated.css: retired names from each migration, kept as aliases until their removal release ----
// Aliases resolve once on :root, so they never follow a theme or mode set on a subtree: one more reason to migrate.
// The 0.14.0 component-scoped names were removed in 0.16.0 as announced; their map stays in tokens/migrations/ for
// anyone upgrading from 0.13 or earlier.
const MIGRATIONS = [
  ['0.16.0-dark-mode.json', 'Deprecated in 0.16.0, removed in 0.17.0: Typography colour tokens, replaced by the Color roles (they follow Light / Dark).'],
];
const depLines = ['/* Generated by scripts/build-tokens.mjs from tokens/migrations/. Replace each name with its target (see the',
  '   migration maps); nothing in this package uses them. */', ':root {'];
for (const [file, note] of MIGRATIONS) {
  const migUrl = new URL(`../tokens/migrations/${file}`, import.meta.url);
  if (!existsSync(migUrl)) continue;
  depLines.push(`  /* ${note} */`);
  for (const [old, { to, mode }] of Object.entries(JSON.parse(readFileSync(migUrl)).map)) {
    if (old === to) continue;
    depLines.push(`  ${cssName(old)}: var(${cssName(to)}${mode ? `--${mode}` : ''});`);
  }
}
depLines.push('}', '');
writeFileSync(new URL('../src/styles/tokens-deprecated.css', import.meta.url), depLines.join('\n'));

// ---- DESIGN.md front matter (machine-readable tokens for Claude Code and other tools) ----
const designUrl = new URL('../DESIGN.md', import.meta.url);
if (existsSync(designUrl)) {
  const primitives = src.Primitives;
  // Values shown for the default brand (Natural); a palette step resolves through Brand to its primitive.
  const resolve = (token) => {
    while (token.alias) token = primitives[token.alias] ?? src.Brand?.[token.alias]?.modes?.Natural;
    return token.type === 'COLOR' ? token.value : px(token.value);
  };
  const q = (s) => JSON.stringify(s);
  const fm = [
    '---',
    '# Generated by `npm run tokens` from tokens/figma-variables.json. Do not edit by hand.',
    'name: Natural Design System',
    'brand: Natural',
    `version: ${pkg.version}`,
    'description: Warm, material-first UI for an online store of nature-based decorative and functional goods.',
    'figma: https://www.figma.com/design/84MjZXozBoKCvf9lwIU5pu/Natural-Design-System',
    'storybook: https://chris-terterian.github.io/natural-design-system/',
    'repository: https://github.com/chris-terterian/natural-design-system',
    'standard: WCAG 2.2 AA',
    'css_prefix: --nds-',
    'font: { family: Inter, weights: [400, 600, 700], fallback: system-ui }',
    'tiers: [Primitives, Brand, Color, Dimension, Layout, Typography, Component]',
    'modes: { Brand: { Natural: default, Tide: "data-nds-brand=tide" }, Color: { Light: default, Dark: "data-nds-theme=dark, or data-nds-theme=system + OS dark mode" }, Layout: { Desktop: default, Mobile: "max-width 767px, data-nds-mode=mobile, or --<token>--mobile" }, Typography: same as Layout, Component: same as Layout }',
    'tokens:',
  ];
  for (const [collection, vars] of collections) {
    fm.push(`  ${q(collection)}:`);
    for (const [name, token] of Object.entries(vars)) {
      if (token.modes) {
        const parts = Object.entries(token.modes).map(([m, t]) => `${m}: { value: ${q(resolve({ ...token, ...t }))}, ref: ${q(t.alias)} }`);
        fm.push(`    ${q(name)}: { ${parts.join(', ')}, css: ${q(cssName(name))} }`);
      } else if (token.alias) {
        fm.push(`    ${q(name)}: { value: ${q(resolve(token))}, ref: ${q(token.alias)}, css: ${q(cssName(name))} }`);
      } else {
        fm.push(`    ${q(name)}: { value: ${q(resolve(token))}, css: ${q(cssName(name))} }`);
      }
    }
  }
  fm.push('---');
  const body = readFileSync(designUrl, 'utf8').replace(/^---\n[\s\S]*?\n---\n/, '');
  writeFileSync(designUrl, `${fm.join('\n')}\n${body}`);
}
// ---- Story UI docs: generated copies, so the AI reads the same brief and tokens as people do ----
const storyUiDocs = new URL('../story-ui-docs/', import.meta.url);
if (existsSync(storyUiDocs)) {
  const note = '<!-- Generated by `npm run tokens` from DESIGN.md. Do not edit here; edit DESIGN.md. -->\n';
  writeFileSync(new URL('guidelines/natural-design-system.md', storyUiDocs), note + readFileSync(designUrl, 'utf8'));
  writeFileSync(new URL('tokens/tokens.json', storyUiDocs), JSON.stringify(src, null, 2) + '\n');
}
console.log('tokens.css, tokens-deprecated.css, DESIGN.md front matter and Story UI docs written');
